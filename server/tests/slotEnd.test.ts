/** Модульные тесты времени конца слота. */

import { describe, expect, it } from 'vitest';

import { slotEnd } from '../src/slotEnd.js';

describe('время конца слота', () => {
  it('прибавляет длительность к времени начала', () => {
    expect(slotEnd('10:00:00', 45)).toBe('10:45:00');
    expect(slotEnd('09:30:00', 30)).toBe('10:00:00');
    expect(slotEnd('18:05:00', 55)).toBe('19:00:00');
  });

  it('сохраняет секунды времени начала', () => {
    expect(slotEnd('10:15:30', 30)).toBe('10:45:30');
  });

  it('возвращает то же время при нулевой длительности', () => {
    expect(slotEnd('00:00:00', 0)).toBe('00:00:00');
  });

  it('не переносит время через полночь: конец суток остаётся видимым', () => {
    // Слот живёт внутри одних суток, переноса на следующий день нет.
    expect(slotEnd('23:45:00', 15)).toBe('24:00:00');
  });
});
